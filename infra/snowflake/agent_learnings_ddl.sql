-- Source Mapping Agent Learnings View
CREATE OR REPLACE VIEW FFP_HDP_CRM_MIG_DB_DEV.SCH_STTM_METADATA.V_SOURCE_MAPPING_LEARNINGS AS
SELECT
    LEARNING_ID,
    AGENT_TYPE,
    LEARNING_TYPE,
    LEARNING_KEY,
    SUMMARY AS SEARCH_TEXT,
    CONFIDENCE,
    ENTITY_TYPE,
    ENTITY_IDS,
    ATTRIBUTES,
    TAGS,
    USAGE_COUNT,
    SUCCESS_COUNT,
    CASE WHEN USAGE_COUNT > 0 THEN SUCCESS_COUNT::FLOAT / USAGE_COUNT ELSE NULL END AS SUCCESS_RATE,
    CREATED_AT,
    LAST_USED_AT,
    -- Composite score for ranking (confidence + success rate + recency)
    CONFIDENCE * 0.4 +
    COALESCE(CASE WHEN USAGE_COUNT > 0 THEN SUCCESS_COUNT::FLOAT / USAGE_COUNT ELSE 0.5 END, 0.5) * 0.4 +
    (1 - DATEDIFF('day', COALESCE(LAST_USED_AT, CREATED_AT), CURRENT_TIMESTAMP()) / 365.0) * 0.2 AS RELEVANCE_SCORE
FROM FFP_HDP_CRM_MIG_DB_DEV.SCH_STTM_METADATA.TBL_AGENT_LEARNINGS
WHERE AGENT_TYPE = 'SOURCE_MAPPING'
  AND STATUS = 'active';

