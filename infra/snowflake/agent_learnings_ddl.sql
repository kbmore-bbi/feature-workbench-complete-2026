-- Create dedicated agent learnings table
CREATE TABLE IF NOT EXISTS FFP_HDP_CRM_MIG_DB_DEV.SCH_STTM_METADATA.TBL_AGENT_LEARNINGS (
    LEARNING_ID         VARCHAR(64)     NOT NULL,
    AGENT_TYPE          VARCHAR(64)     NOT NULL,  -- 'SOURCE_MAPPING', 'TRANSFORMATION_RULE', 'STTM_BUILDER', 'CONVERSATION'
    LEARNING_TYPE       VARCHAR(64)     NOT NULL,  -- 'mapping_acceptance', 'mapping_correction', 'transformation_pattern', etc.
    LEARNING_KEY        VARCHAR(256),              -- For deduplication (hash of key attributes)
    SUMMARY             TEXT            NOT NULL,  -- Human-readable summary for search
    CONFIDENCE          FLOAT           DEFAULT 0.5,
    ENTITY_TYPE         VARCHAR(64),               -- 'mapping_row', 'transformation', 'sttm', 'project'
    ENTITY_IDS          VARIANT,                   -- {project_id, sttm_id, mapping_id, etc.}
    ATTRIBUTES          VARIANT         NOT NULL,  -- Agent-specific learning data
    TAGS                ARRAY,                     -- For filtering: ['pattern:customer_id_mapping', 'rule:CAST', etc.]
    USAGE_COUNT         INTEGER         DEFAULT 0, -- How many times this learning was applied
    SUCCESS_COUNT       INTEGER         DEFAULT 0, -- How many times usage led to acceptance
    LAST_USED_AT        TIMESTAMP_NTZ,
    CREATED_AT          TIMESTAMP_NTZ   DEFAULT CURRENT_TIMESTAMP(),
    CREATED_BY          VARCHAR(128),
    STATUS              VARCHAR(32)     DEFAULT 'active',  -- 'active', 'deprecated', 'superseded'
    SUPERSEDED_BY       VARCHAR(64),               -- Learning ID that replaced this one

    CONSTRAINT PK_AGENT_LEARNINGS PRIMARY KEY (LEARNING_ID)
)
COMMENT = 'Per-agent learning storage for specialized recommendations and pattern matching.';

-- Index for fast agent-specific queries
CREATE INDEX IF NOT EXISTS IDX_AGENT_LEARNINGS_TYPE
    ON FFP_HDP_CRM_MIG_DB_DEV.SCH_STTM_METADATA.TBL_AGENT_LEARNINGS(AGENT_TYPE, LEARNING_TYPE, STATUS);

CREATE INDEX IF NOT EXISTS IDX_AGENT_LEARNINGS_KEY
    ON FFP_HDP_CRM_MIG_DB_DEV.SCH_STTM_METADATA.TBL_AGENT_LEARNINGS(LEARNING_KEY);

