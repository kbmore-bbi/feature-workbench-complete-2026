-- Record a new learning
CREATE OR REPLACE PROCEDURE FFP_HDP_CRM_MIG_DB_DEV.SCH_STTM_METADATA.SP_RECORD_AGENT_LEARNING(
    P_AGENT_TYPE VARCHAR,
    P_LEARNING_TYPE VARCHAR,
    P_SUMMARY VARCHAR,
    P_ATTRIBUTES VARIANT,
    P_ENTITY_TYPE VARCHAR DEFAULT NULL,
    P_ENTITY_IDS VARIANT DEFAULT NULL,
    P_TAGS ARRAY DEFAULT NULL,
    P_CONFIDENCE FLOAT DEFAULT 0.7,
    P_CREATED_BY VARCHAR DEFAULT NULL
)
RETURNS VARCHAR
LANGUAGE SQL
AS
$$
DECLARE
    v_learning_id VARCHAR;
    v_learning_key VARCHAR;
BEGIN
    -- Generate learning ID
    v_learning_id := 'lrn_' || UUID_STRING();

    -- Generate learning key from attributes for deduplication
    v_learning_key := MD5(
        COALESCE(P_AGENT_TYPE, '') || '|' ||
        COALESCE(P_LEARNING_TYPE, '') || '|' ||
        COALESCE(TO_VARCHAR(P_ATTRIBUTES), '')
    );

    -- Check for existing similar learning
    IF EXISTS (
        SELECT 1 FROM FFP_HDP_CRM_MIG_DB_DEV.SCH_STTM_METADATA.TBL_AGENT_LEARNINGS
        WHERE LEARNING_KEY = v_learning_key AND STATUS = 'active'
    ) THEN
        -- Update existing learning with higher confidence
        UPDATE FFP_HDP_CRM_MIG_DB_DEV.SCH_STTM_METADATA.TBL_AGENT_LEARNINGS
        SET
            CONFIDENCE = LEAST(1.0, CONFIDENCE + 0.05),
            USAGE_COUNT = USAGE_COUNT + 1,
            LAST_USED_AT = CURRENT_TIMESTAMP()
        WHERE LEARNING_KEY = v_learning_key AND STATUS = 'active';

        SELECT LEARNING_ID INTO v_learning_id
        FROM FFP_HDP_CRM_MIG_DB_DEV.SCH_STTM_METADATA.TBL_AGENT_LEARNINGS
        WHERE LEARNING_KEY = v_learning_key AND STATUS = 'active'
        LIMIT 1;
    ELSE
        -- Insert new learning
        INSERT INTO FFP_HDP_CRM_MIG_DB_DEV.SCH_STTM_METADATA.TBL_AGENT_LEARNINGS (
            LEARNING_ID, AGENT_TYPE, LEARNING_TYPE, LEARNING_KEY, SUMMARY,
            CONFIDENCE, ENTITY_TYPE, ENTITY_IDS, ATTRIBUTES, TAGS, CREATED_BY
        ) VALUES (
            v_learning_id, P_AGENT_TYPE, P_LEARNING_TYPE, v_learning_key, P_SUMMARY,
            P_CONFIDENCE, P_ENTITY_TYPE, P_ENTITY_IDS, P_ATTRIBUTES, P_TAGS, P_CREATED_BY
        );
    END IF;

    RETURN v_learning_id;
END;
$$;

-- Track learning usage and success
CREATE OR REPLACE PROCEDURE FFP_HDP_CRM_MIG_DB_DEV.SCH_STTM_METADATA.SP_TRACK_LEARNING_USAGE(
    P_LEARNING_ID VARCHAR,
    P_WAS_SUCCESSFUL BOOLEAN DEFAULT TRUE
)
RETURNS BOOLEAN
LANGUAGE SQL
AS
$$
BEGIN
    UPDATE FFP_HDP_CRM_MIG_DB_DEV.SCH_STTM_METADATA.TBL_AGENT_LEARNINGS
    SET
        USAGE_COUNT = USAGE_COUNT + 1,
        SUCCESS_COUNT = SUCCESS_COUNT + CASE WHEN P_WAS_SUCCESSFUL THEN 1 ELSE 0 END,
        LAST_USED_AT = CURRENT_TIMESTAMP()
    WHERE LEARNING_ID = P_LEARNING_ID;

    RETURN TRUE;
END;
$$;
